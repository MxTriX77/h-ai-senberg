"""Download the raw source files listed in config/sources.yaml into retrieval.raw_dir.

    uv run python -m ingest.download [--layer {1,2}] [--raw-dir DIR] [--manifest FILE]

A file that is present and verified is skipped. Downloads go to `<dest>.part`, resume with HTTP
range requests, and replace `dest` only after the checksum matches. Files with a checksum URL
(regenerated by the publisher) get a sidecar `<dest>.<algo>` holding the verified digest.
Writes `download.log` and a DONE or FAILED marker in the raw directory.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import os
import re
import sys
import time
import urllib.error
import urllib.request
import zlib
from datetime import datetime
from pathlib import Path

from ingest.manifest import HEX_LEN, Entry, ManifestError, load_manifest

CHUNK = 1 << 20
RETRIES = 3
RETRY_DELAY_S = 5.0
TIMEOUT_S = 60
USER_AGENT = "haisenberg-ingest/0.1"


class Log:
    """`[HH:MM:SS] <action> <path>` lines to download.log (fresh per run) and stdout."""

    def __init__(self, raw_dir: Path):
        self.path = raw_dir / "download.log"
        self.path.write_text("", encoding="utf-8")

    def __call__(self, action: str, target: Path | str) -> None:
        line = f"[{datetime.now():%H:%M:%S}] {action:<5} {target}"
        with self.path.open("a", encoding="utf-8") as f:
            f.write(line + "\n")
        print(line, flush=True)


def file_digest(path: Path, algo: str) -> str:
    h = hashlib.new(algo)
    with path.open("rb") as f:
        while block := f.read(CHUNK):
            h.update(block)
    return h.hexdigest()


def gzip_intact(path: Path) -> bool:
    """True if the whole gzip stream decompresses and every CRC/length check passes."""
    try:
        with gzip.open(path, "rb") as f:
            while f.read(CHUNK):
                pass
        return True
    except (OSError, EOFError, zlib.error):
        return False


def sidecar(path: Path, algo: str) -> Path:
    return path.with_name(f"{path.name}.{algo}")


def read_sidecar(path: Path, algo: str) -> str | None:
    side = sidecar(path, algo)
    if not side.is_file():
        return None
    m = re.search(rf"\b[0-9a-f]{{{HEX_LEN[algo]}}}\b", side.read_text(encoding="utf-8"))
    return m.group(0) if m else None


def write_sidecar(path: Path, algo: str, digest: str) -> None:
    sidecar(path, algo).write_text(f"{digest}  {path.name}\n", encoding="utf-8")


def _open(url: str, start: int = 0):
    headers = {"User-Agent": USER_AGENT}
    if start:
        headers["Range"] = f"bytes={start}-"
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=TIMEOUT_S)


def fetch_checksum(entry: Entry) -> str | None:
    """The publisher's current digest from the entry's checksum URL, or None on failure."""
    for attempt in range(RETRIES + 1):
        try:
            with _open(entry.checksum_url) as resp:
                text = resp.read().decode("utf-8", "replace")
            m = re.search(rf"\b[0-9a-f]{{{HEX_LEN[entry.algo]}}}\b", text)
            return m.group(0) if m else None
        except (urllib.error.URLError, OSError):
            if attempt < RETRIES:
                time.sleep(RETRY_DELAY_S * (attempt + 1))
    return None


def fetch(url: str, part: Path) -> bool:
    """Download url into part, resuming from its current size. True when the transfer finished."""
    for attempt in range(RETRIES + 1):
        start = part.stat().st_size if part.exists() else 0
        try:
            with _open(url, start) as resp:
                if start and resp.status != 206:  # server ignored the range: start over
                    start = 0
                with part.open("ab" if start else "wb") as f:
                    while block := resp.read(CHUNK):
                        f.write(block)
            return True
        except urllib.error.HTTPError as e:
            if e.code == 416 and start:  # nothing left to send: the .part is complete
                return True
            if e.code == 404:
                return False
        except (urllib.error.URLError, OSError):
            pass
        if attempt < RETRIES:
            time.sleep(RETRY_DELAY_S * (attempt + 1))
    return False


def process(entry: Entry, raw_dir: Path, log: Log) -> bool:
    """Make entry's file present and verified. True on success."""
    dest = entry.path(raw_dir)
    dest.parent.mkdir(parents=True, exist_ok=True)

    if dest.is_file():
        expected = entry.pinned or read_sidecar(dest, entry.algo)
        if expected:
            if file_digest(dest, entry.algo) == expected:
                log("skip", dest)
                return True
        else:  # checksum-URL file without a sidecar, e.g. from the bootstrap download: adopt it
            upstream = fetch_checksum(entry)
            local = file_digest(dest, entry.algo)
            if upstream == local:
                write_sidecar(dest, entry.algo, local)
                log("skip", dest)
                return True
            if dest.suffix == ".gz" and gzip_intact(dest):
                write_sidecar(dest, entry.algo, local)
                log("kept", dest)
                return True

    expected = entry.pinned or fetch_checksum(entry)
    if not expected:
        log("FAIL", dest)
        return False
    part = dest.with_name(dest.name + ".part")
    for _ in range(2):
        log("start", dest)
        if not fetch(entry.url, part):
            log("FAIL", dest)
            return False
        log("done", dest)
        if file_digest(part, entry.algo) == expected:
            os.replace(part, dest)
            if entry.checksum_url:
                write_sidecar(dest, entry.algo, expected)
            log("ok", dest)
            return True
        log("BADSUM", dest)
        part.unlink()
    return False


def run(manifest: Path, raw_dir: Path, layer: int | None = None) -> bool:
    """Process every entry (or one layer's). Writes DONE or FAILED. True if all verified."""
    entries = [e for e in load_manifest(manifest) if layer is None or e.layer == layer]
    raw_dir.mkdir(parents=True, exist_ok=True)
    for marker in ("DONE", "FAILED"):
        (raw_dir / marker).unlink(missing_ok=True)
    log = Log(raw_dir)
    ok = True
    for entry in entries:
        ok = process(entry, raw_dir, log) and ok
    marker = raw_dir / ("DONE" if ok else "FAILED")
    marker.write_text(f"{datetime.now():%Y-%m-%d %H:%M:%S}\n", encoding="utf-8")
    print(f"{marker.name}: {len(entries)} entries, see {log.path}")
    return ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--layer", type=int, choices=(1, 2), help="only this layer's files")
    parser.add_argument("--raw-dir", type=Path, help="default: retrieval.raw_dir from the config")
    parser.add_argument("--manifest", type=Path, help="default: config/sources.yaml in the project")
    args = parser.parse_args(argv)

    raw_dir, manifest = args.raw_dir, args.manifest
    if raw_dir is None or manifest is None:
        from haisenberg.config import ConfigError, load_config

        try:
            cfg = load_config()
        except ConfigError as e:
            print(f"error: {e}", file=sys.stderr)
            return 2
        raw_dir = raw_dir or cfg.retrieval.raw_dir
        manifest = manifest or cfg.root / "config" / "sources.yaml"
    try:
        return 0 if run(manifest, raw_dir, args.layer) else 1
    except ManifestError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
